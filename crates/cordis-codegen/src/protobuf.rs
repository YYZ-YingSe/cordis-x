//! Invoke maintained data generators. Cordis never emits message fields/codecs.
use crate::{Diagnostic, Module, Result, backend::Backend, output::Files};
use base64::{Engine, engine::general_purpose::STANDARD};
use prost::Message;
use std::{path::Path, process::Command};
fn collect(root: &Path, path: &Path, files: &mut Files) -> Result<()> {
    for entry in std::fs::read_dir(path).map_err(|e| Diagnostic::new("generated files", e))? {
        let path = entry
            .map_err(|e| Diagnostic::new("generated files", e))?
            .path();
        if path.is_dir() {
            collect(root, &path, files)?;
        } else {
            files.add(
                crate::paths::relative_name(path.strip_prefix(root).unwrap())?,
                std::fs::read_to_string(&path)
                    .map_err(|e| Diagnostic::new(path.display().to_string(), e))?,
            )?;
        }
    }
    Ok(())
}
pub fn generate(
    module: &Module,
    backends: &[&dyn Backend],
    tools: &crate::GeneratorTools,
) -> Result<Files> {
    let temp = tempfile::tempdir().map_err(|e| Diagnostic::new("temporary directory", e))?;
    let generated = temp.path().join("generated");
    std::fs::create_dir(&generated).map_err(|e| Diagnostic::new("generated files", e))?;
    for backend in backends {
        let name = backend.name();
        let output = generated.join(name).join("proto");
        std::fs::create_dir_all(&output).map_err(|e| Diagnostic::new(name, e))?;
        if name == "rust" {
            let mut fds = prost_types::FileDescriptorSet::decode(module.descriptor.as_slice())
                .map_err(|e| Diagnostic::new("descriptor", e))?;
            fds.file.retain(|f| {
                f.name() != "google/protobuf/descriptor.proto" && f.name() != "cordis/options.proto"
            });
            let mut config = prost_build::Config::new();
            for (package, path) in &module.rust_packages {
                config.extern_path(format!(".{package}"), path);
            }
            config
                .compile_well_known_types()
                .out_dir(&output)
                .include_file("_messages.rs")
                .btree_map(["."])
                .bytes(["."])
                .compile_fds(fds)
                .map_err(|e| Diagnostic::new("prost-build", e))?;
        } else {
            let mut command = Command::new(&tools.protoc);
            for path in &module.includes {
                command.arg("-I").arg(path);
            }
            if name == "cpp" {
                command.arg(format!("--cpp_out={}", output.display()));
            } else if name == "typescript" {
                tools.configure_es(&mut command, temp.path())?;
                command
                    .arg(format!("--es_out={}", output.display()))
                    .arg("--es_opt=target=ts,import_extension=ts,erasable_syntax=true");
            } else {
                return Err(Diagnostic::new(name, "unsupported protobuf generator"));
            }
            let result = command
                .args(&module.files)
                .output()
                .map_err(|e| Diagnostic::new(name, e))?;
            if !result.status.success() {
                return Err(Diagnostic::new(
                    name,
                    String::from_utf8_lossy(&result.stderr),
                ));
            }
        }
    }
    if backends.iter().any(|b| b.name() == "rust") {
        let directory = generated.join("rust/proto");
        for entry in
            std::fs::read_dir(&directory).map_err(|e| Diagnostic::new("rust visitor", e))?
        {
            let path = entry
                .map_err(|e| Diagnostic::new("rust visitor", e))?
                .path();
            if path.file_name().unwrap() == "_messages.rs" {
                continue;
            }
            let text =
                std::fs::read_to_string(&path).map_err(|e| Diagnostic::new("rust visitor", e))?;
            let mut syntax =
                syn::parse_file(&text).map_err(|e| Diagnostic::new("rust visitor", e))?;
            crate::validation::generate(
                module,
                path.file_stem().unwrap().to_str().unwrap(),
                &mut syntax.items,
            )?;
            std::fs::write(
                path,
                String::from(
                    "// @generated by prost-build; logical validation by cordis-codegen.\n",
                ) + &prettyplease::unparse(&syntax),
            )
            .map_err(|e| Diagnostic::new("rust visitor", e))?;
        }
    }
    let mut files = Files::default();
    collect(&generated, &generated, &mut files)?;
    files.add(
        "resources/schema.base64",
        STANDARD.encode(&module.descriptor) + "\n",
    )?;
    Ok(files)
}
