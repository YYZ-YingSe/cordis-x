//! Transferable references to scope-owned objects. The registry stores weak
//! resource capabilities; the existing resource effect owns admission, draining
//! and cleanup. Passing a reference never changes its implementation or binds it
//! to a newer activation with the same service name.
use crate::runtime::Authority;
use crate::{BoxFuture, Context, Error, Resource, Result, WeakResource, protected};
use std::{
    any::Any,
    collections::BTreeMap,
    future::Future,
    sync::{Arc, Mutex},
};

/// Runtime-local, unguessable reference names are a physical representation of
/// an explicitly transferred capability. They expire with their resource and
/// are not durable identifiers, service selectors or permission declarations.
#[derive(Default)]
pub(crate) struct Registry {
    entries: BTreeMap<String, Arc<dyn Any + Send + Sync>>,
}
struct Slot<T>(Mutex<Option<WeakResource<T>>>);

/// A resolved object keeps its original resource gate. Calls use the *current*
/// caller's Context and the exporting implementation's definition, so passing
/// an object does not accidentally reuse the exporter's caller permissions.
pub struct Reference<T> {
    resource: Resource<T>,
}
impl<T> Clone for Reference<T> {
    fn clone(&self) -> Self {
        Self {
            resource: self.resource.clone(),
        }
    }
}
impl<T: Send + Sync + 'static> Reference<T> {
    pub async fn call<R, F>(&self, caller: &Context, call: F) -> Result<R>
    where
        R: Send + 'static,
        F: for<'a> FnOnce(&'a T, Context) -> BoxFuture<'a, Result<R>> + Send + 'static,
    {
        if !std::sync::Weak::ptr_eq(&caller.inner, &self.resource.context.inner) {
            return Err(Error::Closed);
        }
        // Both the exporting scope and this caller must still admit work. The
        // object gate also prevents new calls once explicit release starts.
        let mut leases = caller.call_leases()?;
        leases.extend(self.resource.context.call_leases()?);
        leases.push(self.resource.gate.enter(false, false)?);
        let authority = Authority::new(true);
        let definition = self.resource.context.definition.clone();
        let provider_lease = self.resource.context.definition_lease()?;
        let (mut context, mut pins) =
            caller.for_service(self.resource.context.definition.clone(), authority.clone())?;
        // A reference is a dynamic edge, unlike a statically bound dependency.
        // Effects created by its implementation must retain the actual provider
        // and participate in the existing recovery-cycle checks.
        if definition.activation != context.owner() {
            context.retain_provider(&definition, provider_lease, &mut pins)?;
        } else {
            leases.push(provider_lease);
        }
        let value = self.resource.value.clone();
        let (tx, rx) = tokio::sync::oneshot::channel();
        caller.executor().spawn(async move {
            let outcome = protected(async move { call(&value, context).await }).await;
            authority.expire();
            drop(pins);
            drop(leases);
            let _ = tx.send(outcome);
        });
        rx.await.map_err(|_| Error::RuntimeStopped)?
    }

    /// Explicit disposal has the same shared result and drain-once semantics as
    /// the resource that owns the object. Cloned references address that object;
    /// they do not create independent instances or independent close obligations.
    pub async fn dispose(&self) -> Result<()> {
        self.resource.dispose().await
    }
}

impl Context {
    /// Export one object under this scope. The token is generated by Runtime,
    /// not supplied by a plugin. A receiver must use this same Runtime to resolve
    /// it; a copied token cannot resolve in another host or after restart.
    pub async fn export_reference<T, D, Fut>(
        &self,
        label: impl Into<String>,
        value: T,
        release: D,
    ) -> Result<String>
    where
        T: Send + Sync + 'static,
        D: FnOnce(Arc<T>, Context) -> Fut + Send + 'static,
        Fut: Future<Output = Result<()>> + Send + 'static,
    {
        self.check_authority()?;
        // Keep the owner open until the reference has been published. Otherwise
        // cleanup could win between Resource acquisition and returning its key.
        let _leases = self.call_leases()?;
        let inner = self.inner.upgrade().ok_or(Error::RuntimeStopped)?;
        let mut nonce = [0u8; 32];
        getrandom::fill(&mut nonce)
            .map_err(|e| Error::from(cordis_contract::refused("reference_entropy", e)))?;
        let key: String = nonce.iter().map(|b| format!("{b:02x}")).collect();
        let slot = Arc::new(Slot::<T>(Mutex::new(None)));
        {
            let mut registry = inner.references.lock().unwrap();
            if registry.entries.contains_key(&key) {
                return Err(cordis_contract::refused(
                    "reference_collision",
                    "reference identity collision",
                )
                .into());
            }
            registry.entries.insert(key.clone(), slot.clone());
        }
        let weak = Arc::downgrade(&inner);
        let retired = key.clone();
        let resource = self
            .acquire(
                label,
                async move { Ok(value) },
                move |value, ctx| async move {
                    release(value, ctx).await?;
                    if let Some(inner) = weak.upgrade() {
                        inner.references.lock().unwrap().entries.remove(&retired);
                    }
                    Ok(())
                },
            )
            .await;
        match resource {
            Ok(resource) => {
                *slot.0.lock().unwrap() = Some(resource.downgrade());
                Ok(key)
            }
            Err(error) => {
                inner.references.lock().unwrap().entries.remove(&key);
                Err(error)
            }
        }
    }

    /// Resolve only an object of the adapter's expected host type. The public
    /// method descriptor is checked by the host interface binding before user
    /// code runs; this downcast additionally prevents mixing adapter storage.
    pub fn reference<T: Send + Sync + 'static>(&self, key: &str) -> Result<Reference<T>> {
        self.find_reference(key)?.ok_or(Error::Closed)
    }

    /// Absence is distinct from an expired caller. Idempotent disposal may
    /// accept an already retired key, but must never ignore invalid authority.
    pub fn find_reference<T: Send + Sync + 'static>(
        &self,
        key: &str,
    ) -> Result<Option<Reference<T>>> {
        let _leases = self.call_leases()?;
        let inner = self.inner.upgrade().ok_or(Error::RuntimeStopped)?;
        let Some(slot) = inner.references.lock().unwrap().entries.get(key).cloned() else {
            return Ok(None);
        };
        let slot = Arc::downcast::<Slot<T>>(slot).map_err(|_| Error::Closed)?;
        let resource = slot
            .0
            .lock()
            .unwrap()
            .as_ref()
            .and_then(WeakResource::upgrade)
            .ok_or(Error::Closed)?;
        Ok(Some(Reference { resource }))
    }
}
